from fastapi import APIRouter, HTTPException, Depends, Query
from fastapi.responses import PlainTextResponse, Response
from sqlalchemy.orm import Session
from ..db import get_db, Incident
from ..services.sessions import incident_to_dict
from pydantic import BaseModel

router = APIRouter(prefix="/api/incidents", tags=["incidents"])

class StatusUpdate(BaseModel):
    status: str

@router.get("")
def list_incidents(status: str = None, severity: str = None, machine_id: str = None, q: str = None, from_date: str = None, to_date: str = None, db: Session = Depends(get_db)):
    query = db.query(Incident)
    if status:
        query = query.filter(Incident.status == status)
    if severity:
        query = query.filter(Incident.severity == severity)
    if machine_id:
        query = query.filter(Incident.machine_id == machine_id)
    if from_date:
        query = query.filter(Incident.created_at >= from_date)
    if to_date:
        query = query.filter(Incident.created_at <= to_date)
    items = query.order_by(Incident.created_at.desc()).all()
    out = [incident_to_dict(i) for i in items]
    if q:
        ql = q.lower()
        out = [i for i in out if ql in (i.get("description") or "").lower() or ql in (i.get("machine_id") or "").lower() or ql in (i.get("plant_area") or "").lower()]
    return out

@router.get("/{iid}")
def get_incident(iid: str, db: Session = Depends(get_db)):
    inc = db.query(Incident).filter(Incident.id == iid).first()
    if not inc:
        raise HTTPException(404, "not found")
    return incident_to_dict(inc)

@router.patch("/{iid}")
def update_incident(iid: str, payload: StatusUpdate, db: Session = Depends(get_db)):
    inc = db.query(Incident).filter(Incident.id == iid).first()
    if not inc:
        raise HTTPException(404, "not found")
    inc.status = payload.status
    from datetime import datetime as _dt
    inc.updated_at = _dt.utcnow()
    db.commit()
    db.refresh(inc)
    return incident_to_dict(inc)

@router.get("/{iid}/export")
def export_incident(iid: str, db: Session = Depends(get_db)):
    inc = db.query(Incident).filter(Incident.id == iid).first()
    if not inc:
        raise HTTPException(404, "not found")
    d = incident_to_dict(inc)
    lines = [
        "SHIFT SATHI - INCIDENT REPORT",
        "=" * 40,
        f"Incident ID: {d['id']}",
        f"Machine ID: {d['machine_id']}",
        f"Plant Area: {d['plant_area']}",
        f"Category: {d['category']}",
        f"Severity: {d['severity']}",
        f"Occurred At: {d['occurred_at']}",
        f"Status: {d['status']}",
        f"Confidence: {d['confidence']}",
        "",
        "Description:",
        d['description'] or "",
        "",
        "Sensor Readings: " + (", ".join(d['sensor_readings']) or "none"),
        "Actions Taken: " + (", ".join(d['actions_taken']) or "none"),
        "Missing Information: " + (", ".join(d['missing_info']) or "none"),
        "",
        "Recommended Next Steps:",
    ]
    for s in d['recommended_next_steps']:
        lines.append("- " + s)
    lines += ["", "Transcript:", d['transcript'] or "", "", "Generated by ShiftSathi"]
    content = "\n".join(lines)
    return PlainTextResponse(content, headers={"Content-Disposition": f'attachment; filename="{iid}.txt"'})

@router.get("/export/csv")
def export_csv(db: Session = Depends(get_db)):
    import csv, io
    items = db.query(Incident).order_by(Incident.created_at.desc()).all()
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["id","machine_id","plant_area","category","severity","status","description","created_at"])
    for inc in items:
        w.writerow([inc.id, inc.machine_id, inc.plant_area, inc.category, inc.severity, inc.status, (inc.description or "").replace("\n"," "), inc.created_at])
    return Response(content=buf.getvalue(), media_type="text/csv", headers={"Content-Disposition": 'attachment; filename="incidents.csv"'})

@router.delete("/{iid}")
def delete_incident(iid: str, db: Session = Depends(get_db)):
    inc = db.query(Incident).filter(Incident.id == iid).first()
    if not inc:
        raise HTTPException(404, "not found")
    db.delete(inc)
    db.commit()
    return {"deleted": True}
